# 분석하기 버튼
if st.button("🔍 부상 대처 방법 분석하기", use_container_width=True):
    st.divider()
    
    # 부상 이름에서 괄호 앞부분만 깔끔하게 추출 (예: '타박상 (멍, 부기)' -> '타박상')
    injury_name = selected_injury.split(" ")[0]
    
    # 결과 출력 1: 대처 방법
    st.subheader(f"📋 [{injury_name}] 응급 대처 방법")
    for idx, step in enumerate(injury_data[selected_injury]["steps"], 1):
        st.markdown(f"{idx}. {step}")
        
    # 결과 출력 2: 금지 행동 (경고 박스 활용)
    st.error(f"🚫 **절대 금지 행동:** {injury_data[selected_injury]['forbidden']}")
    
    # 나이대 판별 로직
    if age <= 12:
        age_group = "유소년기 (1~12세)"
    elif age <= 19:
        age_group = "청소년기 (13~19세)"
    elif age <= 39:
        age_group = "청년기 (20~39세)"
    elif age <= 64:
        age_group = "중장년기 (40~64세)"
    else:
        age_group = "노년기 (65~100세)"
        
    # random 라이브러리를 사용하여 해당 연령대의 추천 행동 중 1개를 무작위 선택
